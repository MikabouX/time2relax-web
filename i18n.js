const LANGS = ['fr', 'nl', 'en', 'de'];
let LANG = 'fr';

/** Texte dans la langue courante ; {nom} est remplacé par vars.nom. */
function t(key, vars) {
  const table = STRINGS[LANG] || STRINGS.fr;
  let s = table[key] !== undefined ? table[key] : (STRINGS.fr[key] !== undefined ? STRINGS.fr[key] : key);
  if (vars) s = s.replace(/\{(\w+)\}/g, (m, k) => (vars[k] !== undefined ? vars[k] : m));
  return s;
}

function detectLang() {
  const nav = ((navigator.languages && navigator.languages[0]) || navigator.language || '').toLowerCase();
  const code = nav.slice(0, 2);
  return LANGS.includes(code) ? code : 'en';
}
